import numpy as np
import matplotlib.pyplot as plt
from scipy.signal import butter, filtfilt

# Crear señal de prueba
fs = 1000  # frecuencia de muestreo
t = np.linspace(0, 1, fs)

# Señal original (5 Hz + 50 Hz)
senal = np.sin(2*np.pi*5*t) + 0.5*np.sin(2*np.pi*50*t)

# Agregar ruido
ruido = 0.3 * np.random.randn(len(t))
senal_ruidosa = senal + ruido

# Diseño de filtro pasa bajos
b, a = butter(4, 10/(fs/2), btype='low')

# Aplicar filtro
senal_filtrada = filtfilt(b, a, senal_ruidosa)

# Graficar resultados
plt.figure(figsize=(12,8))

plt.subplot(3,1,1)
plt.plot(t, senal)
plt.title("Señal Original")

plt.subplot(3,1,2)
plt.plot(t, senal_ruidosa)
plt.title("Señal con Ruido")

plt.subplot(3,1,3)
plt.plot(t, senal_filtrada)
plt.title("Señal Filtrada (Pasa Bajos)")

plt.tight_layout()
plt.show()

# FILTRO PASA ALTOS

from scipy.signal import butter, filtfilt

b, a = butter(4, 20/(fs/2), btype='high')

senal_pasa_altos = filtfilt(b, a, senal_ruidosa)

plt.figure(figsize=(10,4))
plt.plot(t, senal_pasa_altos)
plt.title("Filtro Pasa Altos")
plt.xlabel("Tiempo")
plt.ylabel("Amplitud")
plt.grid()
plt.show()

# FILTRO PASA BANDAS

b, a = butter(4, [40/(fs/2), 60/(fs/2)], btype='band')

senal_pasa_bandas = filtfilt(b, a, senal_ruidosa)

plt.figure(figsize=(10,4))
plt.plot(t, senal_pasa_bandas)
plt.title("Filtro Pasa Bandas")
plt.xlabel("Tiempo")
plt.ylabel("Amplitud")
plt.grid()
plt.show()

